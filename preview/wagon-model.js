import {buildCarriageInterior} from '../js/carriage/CarriageInterior.js';
import {box as makeBox} from '../js/graphics/Geometry.js';
const THREE=await import('https://cdn.jsdelivr.net/npm/three@0.161.0/build/three.module.js');
const canvas=document.querySelector('#scene');
const renderer=new THREE.WebGLRenderer({canvas,antialias:true});
renderer.setPixelRatio(1);
renderer.setSize(innerWidth,innerHeight);
renderer.outputColorSpace=THREE.SRGBColorSpace;
const scene=new THREE.Scene();
scene.background=new THREE.Color(0x1c252e);
const camera=new THREE.PerspectiveCamera(65,innerWidth/innerHeight,.1,100);
camera.position.set(0,2.3,4.6);
camera.lookAt(0,2,-8);
scene.add(new THREE.HemisphereLight(0xffffff,0x4a5261,2.2));
const lamp=new THREE.DirectionalLight(0xffffff,1.3);lamp.position.set(2,8,4);scene.add(lamp);
const carriage=new THREE.Group();scene.add(carriage);
const box=(...args)=>makeBox(THREE,...args);
buildCarriageInterior({THREE,carriage,box,getStationName:()=> 'Малиновка'});
let meshes=0;carriage.traverse(o=>{if(o.isMesh)meshes++});
window.wagonModelDiagnostics=()=>({ready:true,meshes,canvasWidth:canvas.width,canvasHeight:canvas.height});
renderer.render(scene,camera);
window.wagonModelReady=true;
window.addEventListener('resize',()=>{camera.aspect=innerWidth/innerHeight;camera.updateProjectionMatrix();renderer.setSize(innerWidth,innerHeight);renderer.render(scene,camera)});
